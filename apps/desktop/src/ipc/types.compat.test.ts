    expectTypeOf<Gen.EqCheck>().toExtend<Hand.EqCheck>();
    expectTypeOf<Hand.Diagnostic>().toExtend<Gen.Diagnostic>();
    expectTypeOf<Gen.Diagnostic>().toExtend<Hand.Diagnostic>();
    expectTypeOf<Hand.SimilarPair>().toExtend<Gen.SimilarPair>();
    expectTypeOf<Gen.SimilarPair>().toExtend<Hand.SimilarPair>();
