    expectTypeOf<Gen.ConversationSummary>().toExtend<Hand.ConversationSummary>();
    expectTypeOf<Hand.FileEntry>().toExtend<Gen.FileEntry>();
    expectTypeOf<Gen.FileEntry>().toExtend<Hand.FileEntry>();
    expectTypeOf<Hand.FileContent>().toExtend<Gen.FileContent>();
    expectTypeOf<Gen.FileContent>().toExtend<Hand.FileContent>();
    expectTypeOf<Hand.WriteResult>().toExtend<Gen.WriteResult>();
    expectTypeOf<Gen.WriteResult>().toExtend<Hand.WriteResult>();
    expectTypeOf<Hand.SearchHit>().toExtend<Gen.SearchHit>();
    expectTypeOf<Gen.SearchHit>().toExtend<Hand.SearchHit>();
    expectTypeOf<Hand.IndexResult>().toExtend<Gen.IndexResult>();
    expectTypeOf<Gen.IndexResult>().toExtend<Hand.IndexResult>();
